  const p = await b.newPage({ viewport: { width: 400, height: 760 }, deviceScaleFactor: 2, colorScheme: 'dark' });
  p.on('pageerror', e => out.errs.push(e.message));
  await p.addInitScript(() => { window.__javaHttp = 'http://127.0.0.1:8098'; localStorage.setItem('lux.host','127.0.0.1'); });
  await p.goto('http://127.0.0.1:8099/index.html'); await p.waitForTimeout(1500);
  await p.click('#tabs button[data-tab=heiz]'); await p.waitForTimeout(300);
  out.summary = await p.innerText('[data-jl="prio"]');
  await p.screenshot({ path: '/root/wp/mock/prio_1_heiz.png' });
  await p.click('[data-jl="prio"]'); await p.waitForTimeout(300);
  out.before = await p.$$eval('.card .li', a => a.map(x => x.innerText.replace(/\s+/g, ' ')));
  await p.click('[data-jf="prio_hz"]'); await p.click('label.opt:has-text("Priorität 1")'); await p.click('#bo'); await p.waitForTimeout(200);
