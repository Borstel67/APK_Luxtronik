"""Generates web/lux_data.js from the decompiled wp.jar (CFR output) + its German language file.

Usage: python3 tools/gen_luxdata.py <cfr-src-dir> <unzipped-jar-dir> <ui-js> <out-js>
All T("Text_x") keys used in the UI script are resolved to German texts.
"""
import json, re, sys

src, jar, ui, out = sys.argv[1:5]
lang = {}
for line in open(f'{jar}/language/lang_de.properties', encoding='latin-1'):
    if '=' in line and not line.lstrip().startswith('#'):
        k, v = line.split('=', 1)
        lang[k.strip()] = v.strip().encode('latin-1').decode('unicode_escape')
T = lambda k: lang.get(k, k)
uni = lambda s: re.sub(r'\\u([0-9a-fA-F]{4})', lambda m: chr(int(m.group(1), 16)), s)

# --- TabelleText: Fehler / Abschaltungen / WP-Typen
tt = open(f'{src}/hilfprogramm/TabelleText.java').read()
def arr(name):
    res = {}
    for m in re.finditer(name + r'\[(\d+)\] = (?:Connect\.getText\("(\w+)"\)|"([^"]*)")', tt):
        res[int(m.group(1))] = T(m.group(2)) if m.group(2) else uni(m.group(3))
    n = max(res) + 1 if res else 0
    return [res.get(i, '') for i in range(n)]
FEHLER, ABSCH, WPTYP = arr('this.TextFehler'), arr('this.Abschaltungen'), arr('this.CWP_bez')
for i, v in enumerate(WPTYP):
    if not v: WPTYP[i] = 'ERC'

# --- Informationen
info_src = open(f'{src}/service/Informationen.java').read()
groups, gname = {}, {}
for m in re.finditer(r'this\.Sammlung\[(\d)\] = new EContainer\("(\w+)"\)|this\.Sammlung\[(\d)\]\.add\(([^;]*)\);', info_src):
    if m.group(1):
        gname[int(m.group(1))] = T(m.group(2)); continue
    g = int(m.group(3)); args = [x.strip() for x in re.split(r',(?![^(]*\))', m.group(4))]
    if args[0].startswith('String.valueOf'):
        args[0] = '"Text_SW_Stand"'; extra = ' SEC'
    else:
        extra = ''
    if not args[0].startswith('"') and args[0] != 'VerdTemp': continue
    key = 'Text_Ansaug_Verdampfer' if args[0] == 'VerdTemp' else args[0].strip('"')
    a = [int(x) if re.fullmatch(r'-?\d+', x) else uni(x.strip('"')) for x in args[1:]]
    e = {'n': T(key) + extra, 'id': a[0], 'v': a[1]}
    if len(a) == 2: e['t'] = 'onoff'
    elif len(a) == 3: e['t'] = {4: 'time', 3: 'typ', 5: 'int', 6: 'sw', 7: 'state', 1: 'ip', 14: 'hex'}.get(a[2], 'raw')
    elif len(a) == 4 and isinstance(a[3], str): e.update(t='num', f=a[2], u=a[3])
    elif len(a) == 4: e.update(t='avg', p=a[2], pv=a[3])
    elif len(a) == 5: e.update(t='num', f=a[2], u=a[3], d=a[4])
    if e['t'] == 'num' and e.get('u', '').strip() == 'bar': e['n'] = 'Druck ' + e['n']
    groups.setdefault(g, []).append(e)
INFO = [{'g': gname[g], 'items': groups[g]} for g in sorted(groups)]

# --- texts used by the UI
keys = set(re.findall(r"['\"](Text_\w+)['\"]", open(ui, encoding='utf-8').read()))
LANG = {k: T(k) for k in sorted(keys)}
missing = [k for k in keys if k not in lang]
if missing: print('WARN missing texts:', missing)

with open(out, 'w', encoding='utf-8') as f:
    f.write('/* generated by tools/gen_luxdata.py from wp.jar – do not edit */\n')
    for name, val in [('LANG', LANG), ('INFO', INFO), ('FEHLER', FEHLER), ('ABSCH', ABSCH), ('WPTYP', WPTYP)]:
        f.write(f'const LUX_{name} = {json.dumps(val, ensure_ascii=False, separators=(",", ":"))};\n')
print(f'{out}: {len(LANG)} texts, {sum(len(g["items"]) for g in INFO)} info items, {len(FEHLER)} errors, {len(ABSCH)} shutdowns, {len(WPTYP)} types')
